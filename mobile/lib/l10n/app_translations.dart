  /// Translate key according to given language code
  static String translate(String langCode, String key, [String? fallback]) {
    final langMap = _strings[langCode] ?? _strings['en']!;
    return langMap[key] ?? _strings['en']?[key] ?? fallback ?? key;
  }

  /// Get translated category name by slug or name
  static String getCategoryName(String langCode, String slugOrName, [String? fallback]) {
    final normalized = slugOrName.trim().toLowerCase();

    // 1. Direct slug match
    var cat = _categories[normalized];

    // 2. Slug match with spaces replaced with hyphens or & stripped
    if (cat == null) {
      final slugified = normalized
          .replaceAll('&', '')
          .replaceAll(RegExp(r'\s+'), '-')
          .replaceAll(RegExp(r'-+'), '-');
      cat = _categories[slugified];
    }

    // 3. Match by English category name or fallback name
    if (cat == null) {
      for (final entry in _categories.values) {
        if ((entry['en']?.toLowerCase() == normalized) ||
            (fallback != null && entry['en']?.toLowerCase() == fallback.trim().toLowerCase())) {
          cat = entry;
          break;
        }
      }
    }

    if (cat == null) return fallback ?? slugOrName;
    return cat[langCode] ?? cat['en'] ?? fallback ?? slugOrName;
  }
